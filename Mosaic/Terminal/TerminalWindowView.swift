/// Structured log for security-relevant events in the terminal layer.
/// Auditable via Console.app (subsystem filter: bundle ID, category: "security").
private let securityLog = Logger(
    subsystem: Bundle.main.bundleIdentifier ?? "com.mosaic.CanvasTerm",
    category: "security"
)

/// Thin subclass that intercepts outgoing key data for broadcast mode
/// while still calling super to let the PTY receive input normally.
final class InterceptingTerminalView: LocalProcessTerminalView {
    var onSendData: (@Sendable (ArraySlice<UInt8>) -> Void)?
    /// Set to true while programmatically sending broadcast data so we don't
    /// re-trigger onSendData and cause an infinite broadcast loop.
    var suppressBroadcast = false

    /// Cached before background dispatch — startProcess calls getWindowSize() which
    /// reads self.frame; NSView.frame must only be accessed on the main thread.
    /// OSAllocatedUnfairLock is Sendable and synchronises access between the main
    /// thread (write/clear) and the background startProcess thread (read via
    /// getWindowSize).
    private let _windowSizeBox = OSAllocatedUnfairLock<winsize?>(initialState: nil)

    nonisolated var cachedWindowSize: winsize? {
        get { _windowSizeBox.withLock { $0 } }
        set { _windowSizeBox.withLock { $0 = newValue } }
    }

    override func getWindowSize() -> winsize {
        cachedWindowSize ?? super.getWindowSize()
    }

    /// Intercept outgoing data for broadcast. `send(source:data:)` is called for both
    /// user keystrokes and SwiftTerm's internal terminal protocol responses (DA1, DA2,
    /// CPR, etc.). Filter out protocol responses by their DEC private prefix (ESC [ ?
    /// or ESC [ >) — these sequences are exclusively generated by the terminal emulator
    /// in response to application queries and are never produced by user keyboard input.
    override func send(source: TerminalView, data: ArraySlice<UInt8>) {
        super.send(source: source, data: data)   // PTY receives input as normal
        guard !suppressBroadcast, Self.shouldBroadcast(data) else { return }
        // Same gate as broadcast eligibility: excludes terminal protocol
        // responses (DA1/DA2/CPR, filtered by shouldBroadcast) and data
        // re-injected here via sendInput (suppressBroadcast) — this fires only
        // for bytes the user actually typed at this terminal's keyboard, which
        // is the reducer's "someone is actively driving this terminal" signal
        // (ADR 007, decision 4's no-keystrokes guard).
        enclosingTerminalWindowView?.recordKeystroke()
        onSendData?(data)
    }

    /// Return `true` if `data` looks like a user keystroke worth broadcasting,
    /// `false` if it's a terminal protocol response that should stay local.
    ///
    /// Filtered prefixes (never produced by user keystrokes):
    /// - `ESC [ ?` / `ESC [ >` — DEC private mode prefixes (DA1, DA2, XTWINOPS, CPR).
    /// - `ESC P / ] / X / ^ / _` — DCS / OSC / SOS / PM / APC introducers.
    /// - 8-bit C1 (`0x90–0x9F`) — single-byte equivalents of the above.
    ///
    /// Empty slices are also rejected — SwiftTerm hands us zero-byte slices on
    /// some paste/insertText paths and subscripting an empty slice traps.
    static func shouldBroadcast(_ data: ArraySlice<UInt8>) -> Bool {
        guard !data.isEmpty else { return false }
        let b0 = data[data.startIndex]
        if b0 == 0x1B, data.count >= 2 {
            let b1 = data[data.startIndex + 1]
            switch b1 {
            case 0x50, 0x5D, 0x58, 0x5E, 0x5F:        // DCS, OSC, SOS, PM, APC
                return false
            case 0x5B where data.count >= 3:           // CSI — DEC private + protocol responses
                let b2 = data[data.startIndex + 2]
                if b2 == 0x3F || b2 == 0x3E { return false }
                // Block intermediate-byte sequences (e.g. DECSTR ESC[!p).
                if b2 >= 0x20 && b2 <= 0x2F { return false }
                // Block CPR (cursor position report ESC[row;colR) — terminal-generated.
                // Verify that last byte is 'R' AND all intermediate bytes are ASCII
                // digits or ';' to avoid suppressing unrelated CSI sequences that
                // happen to end in 0x52 (e.g. DECRQSS responses with arbitrary data).
                if data[data.index(before: data.endIndex)] == 0x52 {
                    let inner = data[(data.startIndex + 2) ..< data.index(before: data.endIndex)]
                    if inner.allSatisfy({ ($0 >= 0x30 && $0 <= 0x39) || $0 == 0x3B }) {
                        return false
                    }
                }
            default: break
            }
        } else if b0 >= 0x90 && b0 <= 0x9F {           // 8-bit C1 (DCS … APC)
            return false
        }
        return true
    }

    var onBell: (() -> Void)?

    /// Rolling-window counter limiting OSC 8 link-open confirmation dialogs to
    /// ≤ 5 per minute. A hostile PTY can emit arbitrary OSC 8 sequences; without
    /// a cap each one forces a modal NSAlert on the main thread, enabling alert
    /// fatigue and a main-thread denial-of-service.
    private var linkOpenCount = 0
    private var linkOpenWindowStart: Double = -.infinity

    /// Trim trailing whitespace from each copied line. SwiftTerm includes empty
    /// cells (padded with spaces) past the last printed character on each row,
    /// which is almost never what the user wants on the clipboard.
    override func copy(_ sender: Any) {
        let raw = getSelection() ?? ""
        guard !raw.isEmpty else {
            super.copy(sender)
            return
        }
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(Self.sanitizeForClipboard(Self.trimTrailingSpacesPerLine(raw)),
                     forType: .string)
    }

    /// Strip Unicode characters that allow malicious PTY output to display one thing
    /// and paste another: bidi overrides/isolates (U+202A–U+202E, U+2066–U+2069) and
    /// the weak directional marks (U+200E LRM, U+200F RLM, U+061C ALM) that can also
    /// nudge visual ordering, zero-width chars (U+200B–U+200D, U+2060, U+FEFF), and
    /// the line/paragraph separators (U+2028/U+2029) that some shells treat as
    /// newlines. Defends against the "innocuous-looking command pastes as
    /// `rm -rf …`" class of attack (cf. iTerm2 2017, CVE-2017-2671).
    ///
    /// NFKC normalisation is applied first to collapse full-width ASCII forms
    /// (ａ→a, ０→0, …) and other compatibility variants that could otherwise
    /// encode visually-identical-but-different shell commands (homoglyph attack).
    /// Note: cross-script confusables (e.g. Cyrillic а vs Latin a) are not
    /// eliminated by NFKC; they require an external confusable database.
    nonisolated static func sanitizeForClipboard(_ text: String) -> String {
        // NFKC: decomposes compatibility characters then recomposes canonically,
        // mapping full-width/half-width variants to standard ASCII equivalents.
        let normalized = (text as NSString).precomposedStringWithCompatibilityMapping
        var out = String.UnicodeScalarView()
        out.reserveCapacity(normalized.unicodeScalars.count)
        for s in normalized.unicodeScalars {
            switch s.value {
            case 0x00...0x08, 0x0B...0x0C, 0x0E...0x1F,      // C0 controls (keep \t \n \r)
                 0x7F,                                         // DEL
                 0x80...0x9F:                                  // 8-bit C1 (incl. ESC variants)
                continue
            case 0x202A...0x202E, 0x2066...0x2069,            // bidi overrides / isolates
                 0x200E, 0x200F, 0x061C,                      // weak bidi marks (LRM/RLM/ALM)
                 0x200B...0x200D, 0x2060, 0xFEFF,             // zero-width
                 0xFE00...0xFE0F,                              // variation selectors
                 0xE0100...0xE01EF,                            // variation selectors supplement
                 0xE0000...0xE007F:                            // Unicode TAG block
                continue
            case 0x2028, 0x2029:                              // line/paragraph separator
                out.append("\n")
            default:
                out.append(s)
            }
        }
        // Cross-script confusable homoglyph mitigation. NFKC handles full-width
        // and compatibility variants but does NOT collapse, e.g., Cyrillic а
        // (U+0430) onto Latin a. If the output contains both ASCII letters and
        // characters from a known confusable script (Cyrillic, Greek, Armenian),
        // strip the confusable-script scalars to prevent visually-identical but
        // byte-different commands from surviving to the clipboard.
        // A string that is purely Cyrillic or purely Greek is left intact.
        let hasASCIILetter = out.contains {
            ($0.value >= 0x41 && $0.value <= 0x5A) || ($0.value >= 0x61 && $0.value <= 0x7A)
        }
        if hasASCIILetter {
            var stripped = String.UnicodeScalarView()
            stripped.reserveCapacity(out.count)
            for s in out {
                let v = s.value
                let isConfusableScript =
                    (v >= 0x0370 && v <= 0x03FF) ||   // Greek and Coptic
                    (v >= 0x0400 && v <= 0x052F) ||   // Cyrillic + supplement
                    (v >= 0x0530 && v <= 0x058F)      // Armenian
                if !isConfusableScript { stripped.append(s) }
            }
            out = stripped
        }
        return String(out)
    }

    nonisolated static func trimTrailingSpacesPerLine(_ text: String) -> String {
        // Operate on UnicodeScalars: in the Character view, "\r\n" is a single
        // grapheme cluster, so splitting on the Character "\n" misses CRLF lines.
        text.unicodeScalars
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { scalars -> String in
                var s = String(String.UnicodeScalarView(scalars))
                let hadCR = s.hasSuffix("\r")
                if hadCR { s.removeLast() }
                while s.last == " " { s.removeLast() }
                if hadCR { s.append("\r") }
                return s
            }
            .joined(separator: "\n")
    }

    /// Clamp and strip control bytes from a notification field before forwarding to
    /// UNUserNotificationCenter — the payload comes from terminal output.
    /// Also strips bidi override/isolate codepoints, the weak directional marks
    /// (LRM/RLM/ALM), and zero-width characters to prevent spoofed notification text
    /// (e.g. RLO-based direction reversal, or a weak mark nudging the visual order of
    /// digits/paths shown in the banner).
    nonisolated static func sanitizeNotificationText(_ s: String, max: Int) -> String {
        var out = String.UnicodeScalarView()
        out.reserveCapacity(min(s.unicodeScalars.count, max))
        var count = 0
        for scalar in s.unicodeScalars where count < max {
            let v = scalar.value
            if v < 0x20 && v != 0x0A { continue }              // strip C0 except newline
            if v >= 0x80 && v <= 0x9F { continue }             // strip 8-bit C1
            // Strip bidi overrides/isolates — prevents RLO spoofing in notification banners.
            if (v >= 0x202A && v <= 0x202E) || (v >= 0x2066 && v <= 0x2069) { continue }
            // Strip weak bidi marks (LRM U+200E, RLM U+200F, ALM U+061C) — same
            // residual Trojan-Source-style spoof risk as the overrides/isolates above.
            if v == 0x200E || v == 0x200F || v == 0x061C { continue }
            // Strip zero-width chars — prevents invisible payload smuggling.
            if (v >= 0x200B && v <= 0x200D) || v == 0x2060 || v == 0xFEFF { continue }
            out.append(scalar)
            count += 1
        }
        return String(out)
    }

    /// Cap an OSC payload's raw byte count before decoding it as UTF-8. Shared
    /// by the OSC 9/777/133 handlers below — all three buffer the full payload
    /// off untrusted PTY output, so every one of them must reject an oversized
    /// payload before spending the allocation on `String(bytes:encoding:)`, not
    /// after.
    /// `nonisolated`: a pure parse of untrusted payload bytes, called from the
    /// `@Sendable` OSC observer closure (off the main actor) before the main-actor hop.
    nonisolated static func decodeOSCPayload(_ data: ArraySlice<UInt8>, maxBytes: Int = 8192) -> String? {
        guard data.count <= maxBytes else { return nil }
        return String(bytes: data, encoding: .utf8) ?? ""
    }

    /// Parse an OSC 9 payload (minus the "9;" prefix) as the iTerm2/Growl
    /// desktop-notification convention. Returns nil for a `4;…` payload — that's
    /// the distinct ConEmu/Windows-Terminal *progress* protocol, which this
    /// handler deliberately ignores rather than surfaces as a notification
    /// (Docs/ADR/008-osc9-notification-override.md).
    nonisolated static func parseOSC9(_ text: String) -> String? {
        guard !text.hasPrefix("4;") else { return nil }
        return text
    }

    /// Parse an OSC 777 payload (minus the "777;" prefix) into (title, body).
    /// Format: `notify;<title>;<body>`. Returns nil for malformed payloads.
    nonisolated static func parseOSC777(_ text: String) -> (title: String, body: String)? {
        let parts = text.split(separator: ";", maxSplits: 2,
                               omittingEmptySubsequences: false).map(String.init)
        guard parts.first == "notify", parts.count >= 2 else { return nil }
        return (title: parts[1], body: parts.count >= 3 ? parts[2] : "")
    }

    /// Parse an OSC 133 FinalTerm shell-integration payload.
    /// A = prompt start, B = command start, C = command executed, D;<exit> = finished.
    enum OSC133Event: Equatable {
        case promptStart
        case commandStart
        case commandFinished(exitCode: Int?)
    }

    nonisolated static func parseOSC133(_ text: String) -> OSC133Event? {
        guard let first = text.first else { return nil }
        switch first {
        case "A": return .promptStart
        case "B": return .commandStart
        case "D":
            let parts = text.split(separator: ";", maxSplits: 1)
            let exit: Int?
            if parts.count > 1, let raw = Int(parts[1]) {
                // Clamp to valid POSIX exit-code range (0–255) so an
                // out-of-range PTY-supplied value cannot propagate to UI
                // arithmetic downstream.
                if (0...255).contains(raw) {
                    exit = raw
                } else {
                    // An integer outside 0–255 is not a valid POSIX exit code.
                    // Log it: differentiates a crafted out-of-range payload from a
                    // legitimately absent exit code (both otherwise yield exit=nil).
                    securityLog.warning("OSC 133 D: PTY exit code \(raw, privacy: .public) out of POSIX range 0–255; treating as unknown")
                    exit = nil
                }
            } else if parts.count > 1 {
                // A non-integer D;<value> payload is malformed; log it so
                // spoofing attempts are distinguishable from a missing exit code.
                securityLog.warning("OSC 133 D: malformed exit code '\(String(parts[1]).prefix(32), privacy: .public)'; treating as unknown")
                exit = nil
            } else {
                exit = nil
            }
            return .commandFinished(exitCode: exit)
        default: return nil
        }
    }

    nonisolated override func bell(source: Terminal) {
        // Deliberately does NOT call super.bell: SwiftTerm's default rings
        // NSSound.beep() for every BEL, which is just noise. The bell instead drives
        // the attention dot / desktop notification (and an optional border flash via
        // flashOnBell) — a routable signal, not an audible ping.
        Task { @MainActor [weak self] in
            self?.onBell?()
        }
    }

    /// Intercept paste to (1) strip embedded bracketed-paste markers so a poisoned
    /// clipboard can't break out of the paste bracket, and (2) warn before sending
    /// multi-line content to the PTY. Each newline acts as Enter and may immediately
    /// execute whatever precedes it, so the newline warning runs when bracketed-paste
    /// mode is off; in bracketed mode the shell defers execution until Enter, so only
    /// the marker strip applies there.
    override func paste(_ sender: Any?) {
        guard let raw = NSPasteboard.general.string(forType: .string) else { return }
        // Remove embedded bracketed-paste markers before delivery. In bracketed-paste
        // mode SwiftTerm wraps the clipboard in ESC[200~ … ESC[201~; a poisoned ESC[201~
        // in the clipboard would otherwise close that bracket early so the bytes after
        // it run as typed input (pastejacking). Stripping the markers leaves the shell
        // to treat the paste as the literal data bracketed mode promises.
        let text = Self.stripBracketedPasteMarkers(raw)

        // v2 removed the mutable `Terminal`; read the one input mode we need from the
        // copied view snapshot. One read reused below so the mode can't change between
        // the newline gate and the bracket wrapping.
        let bracketedPasteMode = terminalStateSnapshot().bracketedPasteMode

        if !bracketedPasteMode, Self.containsPasteNewline(text) {
            let newlineCount = text.unicodeScalars.filter { $0 == "\n" || $0 == "\r" }.count
            let alert = NSAlert()
            alert.messageText = "Paste \(newlineCount) Line\(newlineCount == 1 ? "" : "s")?"
            alert.informativeText = "The clipboard contains newlines. Each newline acts as Enter in the terminal and may execute commands immediately."
            alert.alertStyle = .warning
            alert.addButton(withTitle: "Paste")
            alert.addButton(withTitle: "Cancel")
            guard alert.runModal() == .alertFirstButtonReturn else { return }
        }

        // Deliver the text read (and, when prompted, confirmed) above rather than
        // deferring to super.paste, which re-reads NSPasteboard: a same-user process
        // could swap the clipboard during the modal, pasting newlines the user never
        // saw (TOCTOU). This mirrors SwiftTerm's non-kitty paste path; the one behaviour
        // it drops — kitty key-event encoding for a paste while bracketed mode is off —
        // doesn't apply to literal pasted text.
        if bracketedPasteMode {
            send(data: EscapeSequences.bracketedPasteStart[0...])
            send(txt: text)
            send(data: EscapeSequences.bracketedPasteEnd[0...])
        } else {
            send(txt: text)
        }
    }

    /// Remove the bracketed-paste start/end markers (ESC[200~ / ESC[201~) from text
    /// about to be pasted. See `paste(_:)` for why a clipboard-embedded end marker is
    /// dangerous.
    ///
    /// Loops to a fixpoint rather than stripping once: removing a marker splices its
    /// neighbours together, which can form a fresh marker ("ESC[20" + "ESC[201~" + "1~"
    /// → "ESC[201~"), and stripping an end marker can likewise reveal a start marker.
    /// Each iteration removes ≥1 occurrence and shortens the string, so it terminates.
    nonisolated static func stripBracketedPasteMarkers(_ text: String) -> String {
        let start = "\u{1B}[200~"
        let end = "\u{1B}[201~"
        var out = text
        while out.contains(start) || out.contains(end) {
            out = out.replacingOccurrences(of: start, with: "")
                     .replacingOccurrences(of: end, with: "")
        }
        return out
    }

    /// True when `text` contains a newline that would act as Enter in the terminal.
    /// Tests unicode scalars because Swift collapses "\r\n" into a single Character, so
    /// `contains("\n")`/`contains("\r")` both miss a CRLF-only clipboard.
    nonisolated static func containsPasteNewline(_ text: String) -> Bool {
        text.unicodeScalars.contains { $0 == "\n" || $0 == "\r" }
    }

    /// Open a clicked link — an OSC 8 payload or an implicitly-detected path.
    /// Resolves plain file paths (`Mosaic/App/AppDelegate.swift`, `src/foo.rs:42:10`)
    /// against the terminal's cwd into a real file URL; SwiftTerm's own default opens
    /// via `URL(string:)`, which has no scheme for a bare path and fails with OSStatus
    /// -50. Dangerous URL schemes are refused in `resolveOpenableURL` (ADR-006 scheme
    /// deny-list). There is no per-click confirmation dialog (ADR-006): the deliberate
    /// click is the gate — as in other terminals — and a resolved file opens in its
    /// viewer rather than executing.
    func openResolvedLink(_ link: String) {
        let cwd = enclosingTerminalWindowView?.currentCwd
            ?? FileManager.default.homeDirectoryForCurrentUser.path
        guard let url = Self.resolveOpenableURL(for: link, cwd: cwd) else { return }

        // Bound opens to ≤ 5 / minute so a screen dense with links can't turn a
        // stray double-click into a burst of app launches.
        let now = ProcessInfo.processInfo.systemUptime
        if now - linkOpenWindowStart >= 60 {
            linkOpenCount = 0
            linkOpenWindowStart = now
        }
        guard linkOpenCount < 5 else {
            securityLog.warning("link-open rate-limit reached; dropping open of \(url.absoluteString, privacy: .private)")
            return
        }
        linkOpenCount += 1

        // Re-check existence at open time so a symlink swapped between resolve and
        // open can't redirect the open to a different target.
        if url.isFileURL {
            guard FileManager.default.fileExists(atPath: url.path) else {
                securityLog.warning("link-open aborted: file no longer exists at \(url.path, privacy: .private)")
                return
            }
        }
        securityLog.info("link-open: \(url.absoluteString, privacy: .private)")
        NSWorkspace.shared.open(url)
    }

    /// SwiftTerm v2's link-activation hook. v2 detects the click natively (OSC 8 and
    /// implicitly-detected paths alike) and dispatches it here; `request.link` is the
    /// raw, untrusted link text. We override — rather than call `super`, which would
    /// run SwiftTerm's own `URL(string:)` policy — so every clicked link still goes
    /// through `openResolvedLink`: the ADR-006 scheme deny-list, the file-path
    /// resolution that turns a bare path into a real `file:` URL, the launchable-type
    /// refusal, and the ≤5/min rate cap. See `Docs/ADR/006-link-handling.md`.
    override func requestOpenLink(source _: TerminalView, request: TerminalLinkRequest) {
        openResolvedLink(request.link)
    }

    /// Schemes that are categorically blocked even with the user-confirmation
    /// dialog. The dialog is the primary mitigation; this deny-list provides
    /// defence-in-depth for schemes that must never reach NSWorkspace.
    ///
    /// **Do not flip to an allow-list.** See `Docs/ADR/006-link-handling.md`
    /// for the rationale — custom app schemes (vscode://, slack://, cursor://,
    /// zoom://, obsidian://, …) are legitimate user clicks; the confirmation
    /// dialog in `requestOpenLink` is the social-engineering defence.
    /// `file://` is handled separately via path-resolution below.
    static let deniedLinkSchemes: Set<String> = [
        "javascript", "data", "vbscript",   // script injection
        "jar", "ms-its",                     // historic code-execution vectors
    ]

    /// File types `NSWorkspace.open` *launches or runs* rather than displays.
    /// Refused in `resolveOpenableURL` so a crafted OSC 8 link whose target is one
    /// of these can't turn a single click into code execution — ADR-006's guarantee
    /// is that a clicked file is viewed, never executed. `.app` is a bundle (a
    /// directory), caught by the extension here before the exists-check returns it.
    static let launchableFileExtensions: Set<String> = [
        "app", "command", "terminal", "tool", "workflow", "action",
        "scpt", "scptd", "applescript",
        // Installer packages and preference panes aren't "applications", but
        // NSWorkspace.open still *runs* them — a .pkg/.mpkg launches Installer.app
        // against it and a .prefPane opens System Settings to install it — so a
        // clicked link to one is code execution, not viewing.
        "pkg", "mpkg", "prefpane",
    ]

    /// Installer-package and preference-pane UTIs, refused like `.application` /
    /// `.unixExecutable` below so a renamed or extensionless installer is still
    /// caught by its resolved type, not just its extension.
    private static let launchableContentTypes: [UTType] = [
        UTType("com.apple.installer-package-archive"),
        UTType("com.apple.systempreference.prefpane"),
    ].compactMap { $0 }

    /// True when opening `url` would execute or launch it rather than display it.
    /// Checks the extension deny-set first, then the resolved UTI so an
    /// extensionless Mach-O, app bundle, or installer package is still caught.
    static func isLaunchableFileURL(_ url: URL) -> Bool {
        if launchableFileExtensions.contains(url.pathExtension.lowercased()) { return true }
        guard let type = try? url.resourceValues(forKeys: [.contentTypeKey]).contentType
        else { return false }
        if type.conforms(to: .application) || type.conforms(to: .unixExecutable) { return true }
        return launchableContentTypes.contains { type.conforms(to: $0) }
    }

    /// Pure function so we can unit-test without an NSWorkspace side effect.
    static func resolveOpenableURL(for link: String, cwd: String) -> URL? {
        // Reject pathologically long inputs before any regex / canonicalisation
        // work — both inputs are PTY-controlled and unbounded.
        guard link.utf8.count <= 4096, cwd.utf8.count <= 4096 else { return nil }
        let trimmed = link.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        // Classify as URL vs. filesystem path. URL(string:) parses "hello.txt:42"
        // as scheme="hello.txt" because the scheme grammar allows dots; gate on
        // an explicit "://" so compiler-output paths aren't mis-classified.
        // Opaque schemes like `mailto:` are accepted in the second branch.
        var pathBody = trimmed
        if trimmed.contains("://"), let url = URL(string: trimmed),
           let scheme = url.scheme?.lowercased() {
            if scheme == "file" {
                // Unwrap to the underlying path and fall through so the same
                // canonicalise + exists-check applies.
                pathBody = url.path
            } else if deniedLinkSchemes.contains(scheme) {
                securityLog.warning("link-open blocked: PTY requested denied scheme '\(scheme, privacy: .public)'")
                return nil
            } else {
                return url
            }
        } else if let colon = trimmed.firstIndex(of: ":"),
                  let url = URL(string: trimmed),
                  let scheme = url.scheme?.lowercased(),
                  // Opaque-scheme branch (mailto:, tel:, …). The URL grammar accepts
                  // both a scheme and a `filename:line[:col]` reference here, so
                  // distinguish them two ways: the pre-colon text must be letters only
                  // (so "hello.txt:42", with a dot, is a path), AND the post-colon text
                  // must not be a bare line/column number (so "Makefile:5" — an
                  // extensionless file — is a path, not scheme "makefile", which would
                  // reach NSWorkspace with an unhandled scheme and fail -50 paramErr).
                  trimmed[..<colon].allSatisfy({ $0.isASCII && $0.isLetter }),
                  trimmed[trimmed.index(after: colon)...]
                      .range(of: #"^[0-9]+(?::[0-9]+)?$"#, options: .regularExpression) == nil,
                  !deniedLinkSchemes.contains(scheme) {
            if scheme == "file" {
                // Single-slash `file:/abs/path` (no "://") lands here, not the branch
                // above. Unwrap to the path and fall through so it gets the same
                // canonicalise + exists-check + launchable-type refusal as a bare path,
                // rather than reaching NSWorkspace.open as a raw file: URL.
                pathBody = url.path
            } else {
                return url
            }
        }

        // Strip trailing `:line` or `:line:col` suffix (compiler output).
        let path = pathBody.replacingOccurrences(
            of: #":[0-9]+(?::[0-9]+)?$"#,
            with: "",
            options: .regularExpression)

        // Expand ~ and resolve against cwd for relative paths.
        let expanded = (path as NSString).expandingTildeInPath
        let joined = expanded.hasPrefix("/")
            ? expanded
            : (cwd as NSString).appendingPathComponent(expanded)

        // Canonicalise to fold out `..` segments and symlinks before exists-check.
        // No path-containment check here by design — see
        // `Docs/ADR/006-link-handling.md`. The confirmation dialog in
        // `requestOpenLink` shows the resolved path before NSWorkspace.open().
        let resolved = URL(fileURLWithPath: joined)
            .resolvingSymlinksInPath().standardizedFileURL.path
        var isDir: ObjCBool = false
        guard FileManager.default.fileExists(atPath: resolved, isDirectory: &isDir) else { return nil }
        let fileURL = URL(fileURLWithPath: resolved, isDirectory: isDir.boolValue)

        // Refuse types NSWorkspace would run (`.app`, `.command`, executables) so a
        // click opens a viewer, never code (ADR-006). A refused click is a no-op.
        if isLaunchableFileURL(fileURL) {
            securityLog.warning("link-open blocked: resolved path is a launchable type \(resolved, privacy: .private)")
            return nil
        }
        return fileURL
    }

    /// Route find-panel actions to our custom find bar. SwiftTerm's bundled find UI
    /// (added with the GPU backend) hangs the main thread when shown inside our world-
    /// space terminal layout, so we don't call super.
    override func performFindPanelAction(_ sender: Any?) {
        guard let item = sender as? NSMenuItem,
              let host = enclosingTerminalWindowView else { return }
        switch item.tag {
        case Int(NSFindPanelAction.showFindPanel.rawValue):
            host.showFindBar()
        case Int(NSFindPanelAction.next.rawValue):
            host.findNext()
        case Int(NSFindPanelAction.previous.rawValue):
            host.findPrevious()
        default:
            break
        }
    }

    fileprivate var enclosingTerminalWindowView: TerminalWindowView? {
        var view: NSView? = superview
        while let v = view {
            if let tw = v as? TerminalWindowView { return tw }
            view = v.superview
        }
        return nil
    }
}

