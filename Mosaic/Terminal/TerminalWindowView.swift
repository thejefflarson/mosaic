    // MARK: - Activity: focus & visibility

    /// Observer tokens for `NSApplication.did{Become,Resign}ActiveNotification`,
    /// removed in `deinit`. Per-terminal (mirroring the per-terminal debounce
    /// timer below) rather than a single app-wide dispatcher, so this file stays
    /// self-contained — no back-reference to `CanvasViewController` needed.
    /// `nonisolated(unsafe)`: `NotificationCenter.removeObserver` is documented
    /// thread-safe, and `deinit` isn't guaranteed to run on the main actor even
    /// though the rest of this class is — ARC can deallocate from any thread.
    private nonisolated(unsafe) var appActivationObservers: [NSObjectProtocol] = []

    private func observeAppActivation() {
        let center = NotificationCenter.default
        // `queue: .main` already guarantees this block runs on the main thread;
        // `assumeIsolated` asserts that to the type-checker without a `Task`
        // allocation + extra run-loop hop on every app activation change.
        let handler: @Sendable (Notification) -> Void = { [weak self] note in
            // Derive app-active from the notification identity, not NSApp.isActive:
            // during didResignActive, NSApp.isActive can still read true, which would
            // wrongly keep the active terminal suppressed when you background Mosaic —
            // so a terminal you were looking at would never notify. (ADR 007 §3.)
            let appActive = note.name == NSApplication.didBecomeActiveNotification
            MainActor.assumeIsolated { self?.updateActivityFocusState(appActive: appActive) }
        }
        appActivationObservers = [
            center.addObserver(forName: NSApplication.didBecomeActiveNotification,
                               object: nil, queue: .main, using: handler),
            center.addObserver(forName: NSApplication.didResignActiveNotification,
                               object: nil, queue: .main, using: handler),
        ]
    }

    /// Recomputes the reducer's `becameActiveAndVisible` / `resignedActiveOrHidden`
    /// suppression flag (ADR 007, decision 3) from the three inputs that can
    /// change it: which terminal is focused (`isActive`), whether this one is
    /// culled (`isHidden`), and whether Mosaic is the frontmost app
    /// (`NSApp.isActive`). Called whenever any of the three changes; idempotent
    /// like every other reducer input, so redundant calls (e.g. every terminal
    /// hearing the same app-activation notification) are harmless.
    private func updateActivityFocusState(appActive: Bool = NSApp.isActive) {
        if isActive, !isHidden, appActive {
            reduceActivity(.becameActiveAndVisible)
        } else {
            reduceActivity(.resignedActiveOrHidden)
        }
    }

    // MARK: - Activity: reducer plumbing

    /// Feed `event` into the attention reducer. On an actual flip (many events are
    /// no-ops, e.g. a bell while already `needsAttention`), drives the title-bar dot
    /// straight from the reducer — no fade timer of its own, see `TitleBarView.setActivity`
    /// — and fires `onActivityChange` for other consumers (e.g. the minimap).
    /// Fired when this terminal newly enters `needsAttention` (a genuine raise, not an
    /// exit-code promotion), carrying a title/body for a desktop notification. Not
    /// fired when the OSC 777/9 path already posted its own richer notification for
    /// the same raise (see `justPostedRichNotification`). Wired to a UNUserNotification
    /// by `CanvasViewController`, gated on the app being backgrounded.
    var onNeedsAttention: ((_ title: String, _ body: String) -> Void)?
    private var justPostedRichNotification = false

    @discardableResult
    private func reduceActivity(_ event: ActivityEvent) -> ActivityState {
        let previous = activity.state
        let next = activity.reduce(event)
        if next != previous {
            titleBar.setActivity(next)
            onActivityChange?()
            let wasAttention: Bool = { if case .needsAttention = previous { return true }; return false }()
            if case .needsAttention = next, !wasAttention, !justPostedRichNotification {
                onNeedsAttention?(currentTitle.isEmpty ? "Mosaic" : currentTitle,
                                  attentionNotificationBody(for: next))
            }
        }
        return next
    }

    private func attentionNotificationBody(for state: ActivityState) -> String {
        if case .needsAttention(let code?) = state, code != 0 {
            return "Finished with errors (exit \(code))"
        }
        return "Waiting for you"
    }

    /// Called from the `setProcessOutputHandler` installed in `setupTerminal` after
    /// every parsed output batch (ADR 007, decision 5). The handler fires off the main
    /// actor on SwiftTerm's parse thread and hops here via `Task { @MainActor }`.
    func recordOutputActivity(at time: TimeInterval) {
        reduceActivity(.outputActivity(at: time))
        rescheduleSilenceDebounce()
        // Screen-scrape the agent's state at most ~1×/s while output flows, so we know
        // it was working when the turn later goes quiet (the done-edge is resolved on
        // the settled-output timer below).
        if time - lastAgentClassify >= 1 {
            lastAgentClassify = time
            driveAgentActivity(quietElapsed: false)
        }
    }

    /// Called from `InterceptingTerminalView.send(source:data:)` for bytes the
    /// user typed directly at this terminal.
    func recordKeystroke() {
        reduceActivity(.userKeystroke)
    }

    // MARK: - Activity: silence debounce
    //
    // ADR 007, decision 5: the busy→quiet and idle→attention transitions depend
    // on the *absence* of output, so this uses a single cancellable
    // `DispatchSourceTimer`, rescheduled on every output burst rather than recreated,
    // so a quiet terminal never allocates a new timer and a busy one never leaves a
    // stale deadline pending. A bare `asyncAfter` is deliberately not used: it returns
    // no handle, so an earlier burst's callback can't be invalidated when a later
    // burst reschedules.
    private var silenceDebounce: DispatchSourceTimer?

    private func startSilenceDebounce() {
        let t = DispatchSource.makeTimerSource(queue: .main)
        // No output has arrived yet — leave it with nothing pending until the
        // first burst calls rescheduleSilenceDebounce().
        t.schedule(deadline: .distantFuture)
        t.setEventHandler { [weak self] in
            guard let self else { return }
            // Prefer the agent screen-scrape detector (Claude Code / opencode); only
            // fall back to the generic output-idle heuristic for non-agent terminals.
            if self.driveAgentActivity(quietElapsed: true) { return }
            self.reduceActivity(.quietElapsed(at: ProcessInfo.processInfo.systemUptime))
        }
        t.resume()
        silenceDebounce = t
    }

    /// Push the "went quiet" deadline `TerminalActivityModel.quietThreshold`
    /// seconds out from now. Rescheduling an already-resumed timer source (as
    /// opposed to cancel + recreate) is supported by GCD and keeps this cheap
    /// enough to call on every output burst.
    private func rescheduleSilenceDebounce() {
        silenceDebounce?.schedule(deadline: .now() + TerminalActivityModel.quietThreshold)
    }

    // MARK: - Activity: agent screen-scrape detector
    //
    // Claude Code and opencode don't reliably emit a machine signal on turn
    // completion (see Docs/ADR/007 and the research trail), so — like herdr — we read
    // the visible screen (and OSC title) and recognize the agent's own UI via the
    // vendored manifest engine (Docs/ADR/009). The cross-agent signal is the interrupt
    // affordance ("esc to interrupt"): present ⇒ working; gone after having been
    // working ⇒ turn done. See AgentEngine.
    private var agentWasWorking = false
    private var lastAgentClassify: TimeInterval = 0
    /// Holds the last real (non-`skip_state_update`) activity across drive ticks —
    /// see `SkipStateUpdateHold`. Per-terminal, mutated only from `driveAgentActivity`.
    private var skipStateUpdateHold = SkipStateUpdateHold()

    /// Every bundled agent-detection manifest, compiled once and shared by every
    /// terminal — `ManifestStore.loadBundled()` parses and regex-compiles the bundled
    /// manifests, which are identical app-wide, so a `static let` (not a per-terminal
    /// property) avoids repeating that work for every new terminal window.
    private static let manifestStore = ManifestStore.loadBundled()

    /// The full *visible* screen (every on-screen row, not scrollback) as a single
    /// newline-joined string. Wider than the old bottom-15-lines capture: the engine's
    /// regions (e.g. `prompt_box_body`, `after_last_horizontal_rule`) slice internally
    /// and need more of the screen than a fixed tail to find their anchors.
    private func visibleScreenText() -> String {
        // v2 removed the mutable `Terminal`; the copied view snapshot gives every
        // visible row's text with the same display conversion the old `getLine` walk
        // did by hand (wide-glyph continuation cells skipped, unwritten cells read as
        // spaces, no NUL). The agent-detection logic (ADR-009) is unchanged — only the
        // screen-scrape source moved to the v2 snapshot API.
        termView.terminalStateSnapshot().visibleRows.map(\.text).joined(separator: "\n")
    }

    /// Classify the visible screen and drive the reducer. Returns true when this was an
    /// agent screen we handled (so the caller skips the generic output-idle heuristic) —
    /// including when the PTY foreground process isn't an agent we recognize at all
    /// (`ForegroundAgentIdentifier.identify` returns `nil`), which falls straight
    /// through to the generic tier exactly like an unrecognized screen used to.
    /// The done-edge (working → not working) is resolved only when `quietElapsed` — i.e.
    /// from the settled-output timer — never mid-output.
    @discardableResult
    private func driveAgentActivity(quietElapsed: Bool) -> Bool {
        let now = ProcessInfo.processInfo.systemUptime
        let manifests = Self.manifestStore.manifestsByID
        guard let agentID = ForegroundAgentIdentifier.identify(termView: termView, manifests: manifests),
              let manifest = manifests[agentID] else {
            retainAgent(id: nil, activity: nil)
            return false
        }
        let result = AgentEngine.evaluate(manifest: manifest, screen: visibleScreenText(), title: currentTitle)
        let held = skipStateUpdateHold.apply(result)
        retainAgent(id: agentID, activity: held)
        switch held {
        case .working:
            agentWasWorking = true
            if quietElapsed { rescheduleSilenceDebounce() }   // paused mid-turn; keep watching
            return true
        case .blocked:
            agentWasWorking = false
            reduceActivity(.notification(at: now))            // needs a decision now
            return true
        case .idle:
            // A visible idle prompt means the turn ended — fire the done edge
            // immediately, even mid-output. Agents keep redrawing while idle (cursor,
            // status line), so waiting for the silence timer could miss it entirely.
            if agentWasWorking {
                agentWasWorking = false
                reduceActivity(.notification(at: now))        // turn done → wants you
            }
            return true                                       // an agent screen either way
        case .unknown:
            if quietElapsed, agentWasWorking {
                agentWasWorking = false
                reduceActivity(.notification(at: now))        // was working, now not → done
                return true
            }
            return false                                      // not an agent → generic heuristic
        }
    }

    /// Fires `onActivityChange` on any retained-value change: busy → working flips
    /// `agentWasWorking` without a reducer event, so `ActivityState` alone never
    /// signals it (ADR 010).
    private func retainAgent(id: String?, activity: AgentActivity?) {
        guard id != agentID || activity != lastAgentActivity else { return }
        if activity != lastAgentActivity { stateSince = Date() }
        agentID = id
        lastAgentActivity = activity
        onActivityChange?()
    }

