        termView.appearance = NSAppearance(named: .darkAqua)

        registerOSCHandlers()
        Self.installSharedMonitors()
        startSilenceDebounce()

        startProcess()
    }

    // MARK: - OSC handlers

    /// Keeps the `observeOscEvents` registration alive. Dropping it cancels the
    /// observation (see `TerminalOscObservation`), so it lives as long as the view.
    private var oscObservation: TerminalOscObservation?

    private func registerOSCHandlers() {
        // v2 made the mutable `Terminal` (and `parser.oscHandlers`) internal, so the
        // v1 handler-replacement is gone. v2's public `observeOscEvents(codes:_:)`
        // delivers a copy of each matching OSC sequence while leaving the view's own
        // handling in place. The ADR-008 behaviour is unchanged where it matters:
        //
        //   • OSC 9  — the iTerm2/Growl desktop-notification convention. `9;4;…`
        //     progress payloads are still ignored (parseOSC9 returns nil); every other
        //     payload is a notification routed through `emitNotification`.
        //   • OSC 777 — notify;title;body → the same hardened notification path.
        //   • OSC 133 D — command finished → the attention reducer.
        //
        // The one difference from the v1 override: SwiftTerm v2 keeps its own OSC
        // handling (semantic-prompt tracking for 133, any native 9;4 progress UI)
        // *in addition* to our observer, rather than our handler replacing it. Mosaic
        // surfaces nothing of its own for 9;4, so ADR-008's observable no-op for that
        // payload is preserved; the native semantic-prompt handling we previously
        // suppressed is now simply allowed, which does not change Mosaic's behaviour.
        //
        // `event.payload` is the bytes after the "<code>;" separator — exactly what the
        // v1 `oscHandlers[code]` closures received, so decode/parse is unchanged.
        // Events arrive @Sendable on SwiftTerm's private serial queue; each hops to the
        // main actor before touching reducer/notification state. The returned token
        // must be retained for the observation to stay live (see `oscObservation`).
        //
        // Architectural note (carried from v1): SwiftTerm buffers the entire OSC
        // payload before publishing it, so a crafted PTY stream can still force a large
        // heap allocation before `decodeOSCPayload`'s 8192-byte cap takes effect.
        // Bounding that would require truncating OSC sequences during parsing upstream.
        oscObservation = termView.observeOscEvents(codes: [9, 777, 133]) { [weak self] event in
            let payload = event.payload[...]
            switch event.code {
            case 9:
                guard let text = InterceptingTerminalView.decodeOSCPayload(payload),
                      let message = InterceptingTerminalView.parseOSC9(text) else { return }
                Task { @MainActor [weak self] in
                    self?.emitNotification(title: "", body: message)
                }
            case 777:
                guard let text = InterceptingTerminalView.decodeOSCPayload(payload),
                      let parsed = InterceptingTerminalView.parseOSC777(text) else { return }
                Task { @MainActor [weak self] in
                    self?.emitNotification(title: parsed.title, body: parsed.body)
                }
            case 133:
                guard let text = InterceptingTerminalView.decodeOSCPayload(payload),
                      case .commandFinished(let exit) = InterceptingTerminalView.parseOSC133(text) else { return }
                Task { @MainActor [weak self] in
                    // Also drives the title-bar dot — see reduceActivity.
                    self?.reduceActivity(.commandFinished(exitCode: exit, at: ProcessInfo.processInfo.systemUptime))
                }
            default:
                break
            }
        }
    }

    /// Sanitize, rate-limit, and forward a notification (title, body) pair to
    /// `onNotification` and the attention reducer. Shared by the OSC 9 and OSC
    /// 777 handlers above (Docs/ADR/008-osc9-notification-override.md) so both
    /// routes get identical hardening — same 8 KB payload cap (applied by the
    /// caller before this runs), same sanitizeForClipboard → sanitizeNotificationText
    /// chain, same ≤10/min rate limit — rather than two copies that could drift.
    /// Always call this on the main actor (OSC handlers hop via `Task { @MainActor }`
    /// before calling in).
    private func emitNotification(title rawTitle: String, body rawBody: String) {
        // Chain sanitizeForClipboard before sanitizeNotificationText to also
        // strip bidi overrides (U+202A–U+202E, U+2066–U+2069), zero-width
        // chars, and U+2028/U+2029. setTerminalTitle uses the same chain;
        // notifications forward to UNUserNotificationCenter and should match.
        let title = InterceptingTerminalView.sanitizeNotificationText(
            InterceptingTerminalView.sanitizeForClipboard(rawTitle), max: 128)
        let body = InterceptingTerminalView.sanitizeNotificationText(
            InterceptingTerminalView.sanitizeForClipboard(rawBody), max: 512)
        // Rate-limit: drop notifications exceeding 10 per minute to prevent a PTY
        // process from spamming macOS Notification Centre via OSC 9 or OSC 777.
        // Monotonic systemUptime is immune to NTP steps and clock adjustments.
        let now = ProcessInfo.processInfo.systemUptime
        if now - notificationWindowStart >= 60 {
            notificationCount = 0
            notificationWindowStart = now
        }
        guard notificationCount < 10 else { return }
        notificationCount += 1
        onNotification?(title, body)
        // The OSC path posts its own rich notification via onNotification above, so
        // suppress the generic raise-edge notification for the raise it's about to
        // trigger. Bracketed tightly so a suppressed (active-and-visible) raise still
        // clears the flag and a later non-OSC raise isn't skipped.
        justPostedRichNotification = true
        reduceActivity(.notification(at: now))
        justPostedRichNotification = false
    }

    /// Bound restored scrollback so a single pathological line (e.g.
    /// `cat /dev/urandom | base64 -w0`) can't bloat workspace.json or stall the
    /// next launch when re-fed to the terminal.
    static let maxScrollbackLineChars = 4096
    static let maxScrollbackTotalChars = 256 * 1024

    /// Extract up to `maxLines` of scrollback + visible screen content as plain text.
    ///
    /// v2 removed `getScrollInvariantLine`; the whole active buffer (scrollback +
    /// screen) comes from the view's public `getBufferAsData`, newline-separated. The
    /// capping/trimming is factored into `scrollbackCapture` so it can be unit-tested
    /// without a PTY.
    func extractScrollbackText(maxLines: Int = 300) -> String {
        let rows = Self.bufferRows(from: termView.getBufferAsData())
        return Self.scrollbackCapture(
            rows: rows,
            lineCharCap: Self.maxScrollbackLineChars,
            keepLines: maxLines + termView.terminalDimensions.rows,
            totalCharCap: Self.maxScrollbackTotalChars)
    }

    /// Split a UTF-8 buffer dump (the newline-separated rows `getBufferAsData`
    /// produces) into right-trimmed row strings.
    ///
    /// Splitting on the raw `0x0A` byte, not on a Swift `Character`, matters: a row
    /// that ends in `\r` and the `\n` row separator form one `"\r\n"` grapheme, so a
    /// `Character`-level split would miss that boundary and join two rows (the CRLF
    /// gotcha in `feedback_swift_crlf_split.md`). Splitting on the byte strands that
    /// `\r` on the end of the preceding row, so the trailing trim drops `\r` along with
    /// spaces/tabs — reproducing the old per-row `translateToString(trimRight:)` so
    /// blank-line detection still works.
    nonisolated static func bufferRows(from data: Data) -> [String] {
        data.split(separator: 0x0A, omittingEmptySubsequences: false).map { chunk in
            // Trim on the String, not its `.unicodeScalars` view: because the split was
            // on the raw `0x0A` byte, a chunk can never contain a `\n`, so a trailing
            // `\r` is a standalone Character (no `\r\n` grapheme can span a chunk) and
            // Character-level `removeLast()` is both safe and correct.
            var row = String(decoding: chunk, as: UTF8.self)
            while let last = row.last, last == " " || last == "\t" || last == "\r" {
                row.removeLast()
            }
            return row
        }
    }

    /// Keep the last `keepLines` rows, cap each to `lineCharCap`, drop trailing blank
    /// rows, join with CRLF, and cap the whole thing to `totalCharCap` from the end.
    nonisolated static func scrollbackCapture(rows: [String], lineCharCap: Int, keepLines: Int, totalCharCap: Int) -> String {
        var lines = rows.map { $0.count > lineCharCap ? String($0.prefix(lineCharCap)) : $0 }
        if lines.count > keepLines { lines.removeFirst(lines.count - keepLines) }
        while lines.last?.isEmpty == true { lines.removeLast() }
        let joined = lines.joined(separator: "\r\n")
        return joined.count > totalCharCap ? String(joined.suffix(totalCharCap)) : joined
    }

    // MARK: - Find

    private var matchTotal: Int = 0
    private var matchIndex: Int = 0  // 1-based; 0 means no current match

    // MARK: - Notification rate limiter

    /// Rolling-window counter limiting OSC 777 notifications to ≤ 10 per minute.
    /// Prevents a PTY process from spamming the user's macOS notification centre.
    /// Uses monotonic systemUptime so an NTP step or manual clock change cannot
    /// reset the window and allow an immediate burst bypass.
    private var notificationCount = 0
    private var notificationWindowStart: Double = -.infinity

    /// Rolling-window counter limiting BEL to ≤ 10 per minute.
    /// Mirrors the OSC 777 cap so a PTY cannot bypass the limit by using raw BEL.
    private var bellCount = 0
    private var bellWindowStart: Double = -.infinity

    func showFindBar() {
        let bar = ensureFindBar()
        if bar.searchText.isEmpty,
           let selected = termView.getSelection(),
           !selected.isEmpty,
           !selected.contains("\n") {
            bar.searchText = selected
            recomputeMatchTotal(term: selected)
            if matchTotal > 0 {
                matchIndex = 1
                _ = termView.findNext(selected)
            }
        }
        bar.setMatchInfo(current: matchIndex, total: matchTotal)
        bar.isHidden = false
        bar.focus()
    }

    func hideFindBar() {
        findBar?.isHidden = true
        termView.clearSearch()
        matchTotal = 0
        matchIndex = 0
        window?.makeFirstResponder(termView)
    }

    func findNext() {
        guard let bar = findBar, !bar.searchText.isEmpty else {
            showFindBar()
            return
        }
        // Recompute on every action — scrollback grows under streaming output, and
        // our counter would otherwise drift away from SwiftTerm's internal cursor.
        recomputeMatchTotal(term: bar.searchText)
        guard matchTotal > 0 else {
            matchIndex = 0
            bar.setMatchInfo(current: 0, total: 0)
            return
        }
        matchIndex = matchIndex >= matchTotal ? 1 : matchIndex + 1
        _ = termView.findNext(bar.searchText)
        bar.setMatchInfo(current: matchIndex, total: matchTotal)
    }

    func findPrevious() {
        guard let bar = findBar, !bar.searchText.isEmpty else {
            showFindBar()
            return
        }
        recomputeMatchTotal(term: bar.searchText)
        guard matchTotal > 0 else {
            matchIndex = 0
            bar.setMatchInfo(current: 0, total: 0)
            return
        }
        matchIndex = matchIndex <= 1 ? matchTotal : matchIndex - 1
        _ = termView.findPrevious(bar.searchText)
        bar.setMatchInfo(current: matchIndex, total: matchTotal)
    }

    private func ensureFindBar() -> TerminalFindBar {
        if let bar = findBar { return bar }
        let bar = TerminalFindBar()
        bar.translatesAutoresizingMaskIntoConstraints = false
        bar.isHidden = true
        bar.onSearchChanged = { [weak self] term in
            guard let self else { return }
            if term.isEmpty {
                self.termView.clearSearch()
                self.matchTotal = 0
                self.matchIndex = 0
            } else {
                self.recomputeMatchTotal(term: term)
                if self.matchTotal > 0 {
                    self.matchIndex = 1
                    _ = self.termView.findNext(term)
                } else {
                    self.matchIndex = 0
                    self.termView.clearSearch()
                }
            }
            self.findBar?.setMatchInfo(current: self.matchIndex, total: self.matchTotal)
        }
        bar.onFindNext = { [weak self] in self?.findNext() }
        bar.onFindPrevious = { [weak self] in self?.findPrevious() }
        bar.onClose = { [weak self] in self?.hideFindBar() }
        addSubview(bar)
        NSLayoutConstraint.activate([
            bar.topAnchor.constraint(equalTo: topAnchor, constant: titleBarHeight + 4),
            bar.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -6),
            bar.leadingAnchor.constraint(greaterThanOrEqualTo: leadingAnchor, constant: 6),
            bar.widthAnchor.constraint(lessThanOrEqualToConstant: 420)
        ])
        findBar = bar
        return bar
    }

    /// Count case-insensitive substring occurrences across the entire scrollback +
    /// visible buffer. SwiftTerm's full-buffer match count is internal, so we read the
    /// whole active buffer via the public `getBufferAsData` and tally per line. The
    /// counting (and its DoS caps) is factored into `matchCount` for unit testing.
    private func recomputeMatchTotal(term: String) {
        guard !term.isEmpty else {
            matchTotal = 0
            return
        }
        let rows = Self.bufferRows(from: termView.getBufferAsData())
        matchTotal = Self.matchCount(
            rows: rows,
            term: term,
            perRowCap: Self.maxScrollbackLineChars,
            // Cap at 10 000 rows / 1 MB of scanned text so a PTY that fills scrollback
            // cannot block the main actor for hundreds of ms per find-bar keystroke.
            maxRows: 10_000,
            totalByteCap: 1 * 1024 * 1024)
    }

    /// Count case-insensitive, overlapping-free occurrences of `term` across `rows`,
    /// stopping after `maxRows` rows or `totalByteCap` bytes of (capped, lowercased)
    /// text, whichever comes first.
    nonisolated static func matchCount(rows: [String], term: String, perRowCap: Int, maxRows: Int, totalByteCap: Int) -> Int {
        guard !term.isEmpty else { return 0 }
        let lower = term.lowercased()
        var count = 0
        var bytesScanned = 0
        var scanned = 0
        for row in rows {
            if scanned >= maxRows || bytesScanned > totalByteCap { break }
            scanned += 1
            var s = row.lowercased()
            if s.count > perRowCap { s = String(s.prefix(perRowCap)) }
            bytesScanned += s.utf8.count
            if s.isEmpty { continue }
            var idx = s.startIndex
            while let r = s.range(of: lower, range: idx..<s.endIndex) {
                count += 1
                idx = r.upperBound
            }
        }
        return count
    }

    /// Clear scrollback and screen (Cmd+K behaviour). Feeds ESC sequences directly
    /// to the terminal display — does not send anything to the PTY.
    func clearScrollback() {
        // ESC[H  = cursor home
        // ESC[2J = erase screen
        // ESC[3J = erase saved lines (scrollback)
        termView.feed(byteArray: [0x1B, 0x5B, 0x48,
                                  0x1B, 0x5B, 0x32, 0x4A,
                                  0x1B, 0x5B, 0x33, 0x4A])
    }

    private func startProcess() {
        let settings = TerminalSettings.shared
        applyTerminalSettings(settings)

        var env = ProcessInfo.processInfo.environment
        // Strip variables that commonly hold credentials from Mosaic's own
        // process environment (e.g. API keys injected by CI runners or
        // launch-agent wrappers) so they don't leak into spawned shells.
        // Standard shell variables (PATH, HOME, USER, SHELL, LANG, …) are
        // unaffected. Suffix matching is case-insensitive to catch mixed-case
        // naming conventions.
        // Suffix-based stripping (case-insensitive).
        // "_KEY"    catches OPENAI_KEY, ANTHROPIC_KEY, PRIVATE_KEY, etc.
        // "_AUTH"   catches GH_AUTH, GITHUB_AUTH, etc.
        // "_KEY_ID" catches AWS_ACCESS_KEY_ID, etc.
        let credentialSuffixes = [
            "_TOKEN", "_SECRET", "_API_KEY", "_PASSWORD", "_PASS", "_CREDENTIAL",
            "_KEY", "_AUTH", "_KEY_ID",
        ]
        // Exact-name matching for well-known credential vars whose names don't
        // follow a suffix pattern (e.g. DATABASE_URL, where "_URL" alone is too broad).
        // Covers common 12-factor service connection strings that embed credentials
        // (user:password@host) in the URL itself.
        let exactCredentialNames: Set<String> = [
            "DATABASE_URL",   // PostgreSQL / generic DB
            "REDIS_URL",      // Redis
            "MONGO_URL",      // MongoDB (short form)
            "MONGODB_URL",    // MongoDB (long form)
            "RABBITMQ_URL",   // RabbitMQ AMQP
            "AMQP_URL",       // generic AMQP
            "CELERY_BROKER_URL",
            "CELERY_RESULT_BACKEND",
        ]
        for key in env.keys {
            let upper = key.uppercased()
            if credentialSuffixes.contains(where: { upper.hasSuffix($0) })
                || exactCredentialNames.contains(upper) {
                env.removeValue(forKey: key)
            }
        }
        env["TERM"] = "xterm-256color"
        env["COLORTERM"] = "truecolor"

        // Ensure a UTF-8 locale. When Mosaic is launched from the Finder/`open`
        // (a GUI app), macOS does NOT populate LANG/LC_* — only Terminal.app
        // injects them, from its "Set locale on startup" preference. Without a
        // UTF-8 locale, programs fall back to C/POSIX (ASCII) and mis-encode the
        // terminal's UTF-8 stream, so multi-byte glyphs render as mojibake (em-dash
        // "—" → "‚Äî", claude code's "⏺"/"…" → "‚è∫"/"‚Ä¶").
        //
        // It's not enough to check for *absent* vars: a launchd/`open` environment
        // often carries a present-but-broken value — an empty `LANG=""`, an
        // explicit `LC_CTYPE=C`, or the macOS quirk of a bare `LC_CTYPE=UTF-8` (no
        // language prefix, which is an invalid locale programs reject → fall back to
        // C). So resolve the effective character-type locale by POSIX precedence
        // (LC_ALL > LC_CTYPE > LANG), treating empty values as unset, and only act
        // when it isn't UTF-8.
        func localeValue(_ key: String) -> String? {
            guard let v = env[key], !v.isEmpty else { return nil }
            return v
        }
        let effectiveCType = localeValue("LC_ALL") ?? localeValue("LC_CTYPE") ?? localeValue("LANG")
        let isUTF8 = effectiveCType.map { $0.uppercased().contains("UTF-8") || $0.uppercased().contains("UTF8") } ?? false
        if !isUTF8 {
            let lang = Locale.current.language.languageCode?.identifier ?? "en"
            let region = Locale.current.region?.identifier ?? "US"
            let utf8Locale = "\(lang)_\(region).UTF-8"
            // LC_ALL and LC_CTYPE, if set, override LANG for character type — so a
            // non-UTF-8 one must be cleared, not merely shadowed by setting LANG.
            env.removeValue(forKey: "LC_ALL")
            env.removeValue(forKey: "LC_CTYPE")
            env["LANG"] = utf8Locale
        }

        var isDir: ObjCBool = false
        let cwdExists = FileManager.default.fileExists(atPath: currentCwd, isDirectory: &isDir) && isDir.boolValue
        let cwd = cwdExists ? currentCwd : FileManager.default.homeDirectoryForCurrentUser.path

        let execName = "-" + (shell as NSString).lastPathComponent
        let envList  = env.map { "\($0.key)=\($0.value)" }
        let shellPath = shell
        let scrollbackLines = settings.scrollbackLines
        let cursorStyle = settings.swiftTermCursorStyle

        // Cache window size before background dispatch — startProcess calls getWindowSize()
        // which reads self.frame; that must happen on the main thread.
        termView!.cachedWindowSize = termView!.getWindowSize()

        // Run forkpty on a background thread so the ~2 s atfork-handler cost
        // (libBacktraceRecording) doesn't block the main thread and cause a beachball.
        // SwiftTerm annotates startProcess as @MainActor but the underlying forkpty
        // call is thread-safe; the annotation is overly conservative.
        //
        // NOTE: Swift 6 emits "main actor-isolated method called in nonisolated
        // context" here. We treat this as the documented-acceptable exception in
        // CLAUDE.md (third-party API with an overly strict actor annotation we
        // can't change). `@preconcurrency import SwiftTerm` already downgrades
        // the error to a warning; further suppression would require unsafeBitCast
        // hacks that hurt readability more than the warning does.
        DispatchQueue.global(qos: .userInitiated).async { [termView] in
            termView!.startProcess(
                executable: shellPath,
                args: [],
                environment: envList,
                execName: execName,
                currentDirectory: cwd
            )
            DispatchQueue.main.async {
                // Clear the cached size now that the process is running.
                // sizeChanged() calls getWindowSize() to build the TIOCSWINSZ winsize;
                // from this point it must read the live frame, not the startup snapshot.
                termView!.cachedWindowSize = nil
                termView!.changeScrollback(scrollbackLines)
                termView!.setCursorStyle(cursorStyle)
            }
        }

        // Apply theme and optionally restore scrollback after shell init sequences
        // have run. The 2 s delay is a heuristic; if the shell takes longer to
        // initialize, restored scrollback may still interleave with startup output.
        // A more robust fix would hook OSC 133 A (prompt-start) to trigger
        // restoration, but that requires shells to emit OSC 133 support — not
        // universal enough to rely on as the sole mechanism.
        DispatchQueue.main.asyncAfter(deadline: .now() + 2.0) { [weak self] in
            guard let self else { return }
            self.applyTheme(self.theme)
            if let raw = self.restoredScrollback, !raw.isEmpty {
                self.restoredScrollback = nil
                // Cap restored bytes — workspace.json is untrusted on disk.
                let text = raw.count > Self.maxScrollbackTotalChars
                    ? String(raw.suffix(Self.maxScrollbackTotalChars))
                    : raw
                // Strip all ANSI/OSC escape sequences (incl. 8-bit C1) from the
                // persisted scrollback before re-feeding it. Without this, a tampered
                // workspace.json could inject OSC sequences (OSC 8 hyperlinks, OSC 1337
                // file transfers, title spoofing) into the running terminal.
                // NUL bytes (U+0000) arise from terminal cells never explicitly written
                // (cursor-positioned TUI layouts). Replace them with spaces.
                let safe = TerminalWindowView.stripEscapeSequences(text)
                    .replacingOccurrences(of: "\u{0000}", with: " ")
                // Dim color + italic, then show saved content, then reset.
                // Prepend ST (ESC \) to close any dangling OSC/DCS sequence that
                // stripEscapeSequences may have left at the truncation boundary —
                // without it a bare ESC ] at the end would absorb the SGR reset as
                // the OSC body, leaving the terminal permanently dim/italic.
                let dimmed = "\u{1B}[2;3m" + safe + "\u{1B}\\\u{1B}[0m\r\n"
                self.termView.feed(text: dimmed)
            }
        }
    }

    /// Remove ANSI CSI sequences (`ESC [ … m/A/B/…`), OSC sequences
    /// (`ESC ] … BEL/ST`), and bare `ESC X` two-character sequences from `text`.
    /// Also handles the 8-bit C1 single-byte equivalents (0x9B CSI, 0x9D OSC,
    /// 0x90 DCS, 0x9E PM, 0x9F APC, 0x98 SOS) which xterm-class parsers (including
    /// SwiftTerm) honour and which UTF-8-encode to U+0080–U+009F (two bytes
    /// 0xC2 0x9X). A tampered workspace.json scrollback containing raw 0x9D…BEL
    /// would otherwise inject an OSC sequence when re-fed at launch.
    static func stripEscapeSequences(_ text: String) -> String {
        var result = ""
        result.reserveCapacity(text.count)
        var iter = text.unicodeScalars.makeIterator()
        while let ch = iter.next() {
            // 7-bit ESC-introduced or 8-bit C1 single-byte introducer.
            if ch == "\u{1B}" {
                guard let next = iter.next() else { break }
                consumeEscapeBody(intro: next, iter: &iter)
            } else if (0x80...0x9F).contains(ch.value) {
                // Map C1 to its 7-bit equivalent introducer and consume.
                let mapped: Unicode.Scalar
                switch ch.value {
                case 0x9B: mapped = "["
                case 0x9D: mapped = "]"
                case 0x90: mapped = "P"
                case 0x9E: mapped = "^"
                case 0x9F: mapped = "_"
                case 0x98: mapped = "X"
                default:
                    // Other C1 controls — just drop the single byte.
                    continue
                }
                consumeEscapeBody(intro: mapped, iter: &iter)
            } else {
                result.unicodeScalars.append(ch)
            }
        }
        return result
    }

    /// Consume the body of an escape sequence given its post-introducer class byte.
    /// Mutating because the iterator is advanced.
    private static func consumeEscapeBody(intro: Unicode.Scalar,
                                          iter: inout String.UnicodeScalarView.Iterator) {
        switch intro {
        case "[":
            // CSI: consume until a final byte in 0x40–0x7E.
            while let c = iter.next() {
                if c.value >= 0x40 && c.value <= 0x7E { break }
            }
        case "]", "P", "X", "^", "_":
            // ST-terminated: consume until BEL, ESC \, or 8-bit ST (U+009C).
            var prev: Unicode.Scalar = "\u{00}"
            while let c = iter.next() {
                if c == "\u{07}" || c == "\u{9C}" { break }
                if prev == "\u{1B}" && c == "\\" { break }
                prev = c
            }
        default:
            break       // Two-character escape; introducer already consumed.
        }
    }

    func applyTerminalSettings(_ settings: TerminalSettings) {
        termView.optionAsMetaKey        = settings.optionAsMetaKey
        termView.backspaceSendsControlH = settings.backspaceSendsControlH
        termView.allowMouseReporting    = settings.allowMouseReporting
        termView.useBrightColors        = settings.useBrightColors
        termView.changeScrollback(settings.scrollbackLines)
        termView.setCursorStyle(settings.swiftTermCursorStyle)
    }

    func applyTheme(_ theme: Theme) {
        self.theme = theme
        termView.nativeForegroundColor = theme.terminalForeground
        termView.nativeBackgroundColor = theme.terminalBackground
        termView.font = theme.terminalFont
        termView.feed(text: theme.oscSequences)
        layer?.backgroundColor = theme.terminalBackground.cgColor
        // syncTitleBarColor preserves the broadcast tint when active; calling
        // titleBar.applyTheme directly would clobber it.
        syncTitleBarColor()
        updateBorder()
    }

    private func syncTitleBarColor() {
        if isBroadcast {
            titleBar.layer?.backgroundColor = NSColor(red: 0.15, green: 0.3, blue: 0.15, alpha: 1).cgColor
        } else {
            titleBar.applyTheme(background: theme.terminalBackground, foreground: theme.terminalForeground)
        }
    }

    // MARK: - Resize handles

    private func setupResizeHandles() {
        for edge in ResizeHandleView.Edge.allCases {
            let h = ResizeHandleView(edge: edge)
            h.translatesAutoresizingMaskIntoConstraints = false
            addSubview(h)
            h.installConstraints(in: self)
            h.onResizeBegan = { [weak self] in
                guard let self else { return }
                frameBeforeDrag = frame
            }
            h.onResize = { [weak self] dx, dy in
                self?.handleResize(edge: edge, screenDX: dx, screenDY: dy)
            }
            h.onResizeEnded = { [weak self] in
                guard let self else { return }
                clearSnapGuides?()
                guard frame != frameBeforeDrag else { return }
                onMoveEnded?(frameBeforeDrag, frame)
            }
        }
    }

    private func handleResize(edge: ResizeHandleView.Edge, screenDX: CGFloat, screenDY: CGFloat) {
        guard let cv = canvasView else { return }
        let zoom = cv.currentZoom
        let dx = screenDX / zoom
        // screenDY is window-space y-up; world space is y-down, so negate
        let dy = -screenDY / zoom

        var r = frame
        switch edge {
        case .topLeft:
            r.origin.x += dx; r.size.width -= dx
            r.origin.y += dy; r.size.height -= dy
        case .top:
            r.origin.y += dy; r.size.height -= dy
        case .topRight:
            r.size.width += dx
            r.origin.y += dy; r.size.height -= dy
        case .left:
            r.origin.x += dx; r.size.width -= dx
        case .right:
            r.size.width += dx
        case .bottomLeft:
            r.origin.x += dx; r.size.width -= dx
            r.size.height += dy
        case .bottom:
            r.size.height += dy
        case .bottomRight:
            r.size.width += dx
            r.size.height += dy
        }

        r.size.width  = max(r.size.width,  minSize.width)
        r.size.height = max(r.size.height, minSize.height)

        // Apply edge-aware snapping: call snapFrame to find alignment deltas, then
        // apply each delta to the dimension that's actually moving for this edge.
        if let snap = snapFrame {
            let snapped = snap(r, edge)
            let sdx = snapped.origin.x - r.origin.x
            let sdy = snapped.origin.y - r.origin.y

            let dragsRight  = edge == .right  || edge == .topRight    || edge == .bottomRight
            let dragsLeft   = edge == .left   || edge == .topLeft     || edge == .bottomLeft
            let dragsBottom = edge == .bottom || edge == .bottomLeft  || edge == .bottomRight
            let dragsTop    = edge == .top    || edge == .topLeft     || edge == .topRight

            if dragsRight       { r.size.width  += sdx }
            else if dragsLeft   { r.origin.x    += sdx; r.size.width  -= sdx }
            if dragsBottom      { r.size.height += sdy }
            else if dragsTop    { r.origin.y    += sdy; r.size.height -= sdy }

            r.size.width  = max(r.size.width,  minSize.width)
            r.size.height = max(r.size.height, minSize.height)
        }

        frame = r
        onMoved?()
    }

    // MARK: - Focus

    func focusTerminal() {
        window?.makeFirstResponder(termView)
    }

    // SwiftTerm coalesces redraws behind a 60fps `pendingDisplay` throttle and
    // invalidates only the changed row band via `setNeedsDisplay(region)`. Two
    // failure modes surface in long-running sessions and TUIs:
    //
    //   1. A dropped/stalled main-queue frame leaves the throttle armed
    //      (`pendingDisplay == true`), so rows fed afterwards never repaint until
    //      an unrelated event forces a draw — the classic "nothing renders until
    //      I scroll" freeze.
    // The v1 redraw watchdog (a 30fps timer that cleared `Terminal.getUpdateRange()`
    // and forced a full `needsDisplay` on every unflushed buffer change) is gone with
    // v2. It worked around v1's CoreGraphics `pendingDisplay` throttle and
    // partial-region invalidation; v2 renders through a GPU snapshot pipeline
    // (`FrameDriver`/`RenderLoop`) that owns its own invalidation and display-link
    // scheduling and suspends/resumes on view visibility, so the manual watchdog — and
    // its now-internal `getUpdateRange`/`clearUpdateRange` primitives — have no v2
    // equivalent and no remaining purpose. Repaint after un-culling now relies on the
    // frame driver resuming when the view is unhidden; see the PR's runtime-test
    // checklist item "repaint after un-culling a hidden terminal".

    deinit {
        silenceDebounce?.cancel()
        appActivationObservers.forEach { NotificationCenter.default.removeObserver($0) }
    }

    // MARK: - Input broadcasting

    func sendInput(_ data: Data) {
        let bytes = [UInt8](data)
        termView.suppressBroadcast = true
        termView.send(data: bytes[...])
        termView.suppressBroadcast = false
    }

    // MARK: - Visual state

    func setBroadcastHighlight(_ on: Bool) {
        isBroadcast = on
        syncTitleBarColor()
    }

    func terminate() {
        // Signal the shell to exit cleanly (lets it flush / run exit traps)...
        termView.send(data: [0x04][...])  // Ctrl-D / EOF
        // ...then tear down SwiftTerm's PTY plumbing. This call is essential, not
        // optional: LocalProcessTerminalView.terminate() closes the DispatchIO read
        // channel and cancels the child-process DispatchSource. Those sources are
        // reachable from GCD's global registry and strongly retain this view — and
        // through it the SwiftTerm Terminal, its Buffers, and every scrollback
        // BufferLine. Without it the terminal never deallocates, so each closed
        // terminal's entire scrollback stays resident forever (measured: 5 GB of
        // ~1M BufferLines across ~70 closed terminals after a multi-day session).
        // `leaks` won't flag it — the memory is reachable, not lost.
        termView.terminate()

        // Stop the silence-debounce timer here, deterministically, rather than relying
        // on deinit: the retain chain described above means dealloc can be arbitrarily
        // delayed, and a live timer on a closed terminal wastes wakeups for no observer.
        silenceDebounce?.cancel()
    }
}

// MARK: - LocalProcessTerminalViewDelegate

extension TerminalWindowView: LocalProcessTerminalViewDelegate {
    nonisolated func sizeChanged(source: LocalProcessTerminalView, newCols: Int, newRows: Int) {
        // SIGWINCH is sent automatically by SwiftTerm; nothing extra needed here
    }

    nonisolated func setTerminalTitle(source: LocalProcessTerminalView, title: String) {
        // Cap length and sanitize PTY-supplied title: strip bidi overrides (prevents
        // RLO spoofing) and control bytes (prevents title-bar injection / unbounded
        // allocation). Capping before sanitizing bounds the work done here.
        let raw = title.count > 256 ? String(title.prefix(256)) : title
        let safe = InterceptingTerminalView.sanitizeNotificationText(
            InterceptingTerminalView.sanitizeForClipboard(raw), max: 256)
        Task { @MainActor [weak self] in
            self?.shellReady = true
            self?.currentTitle = safe
            self?.titleBar.titleLabel.stringValue = safe
            self?.syncTitleBarColor()
        }
    }

    nonisolated func hostCurrentDirectoryUpdate(source: TerminalView, directory: String?) {
        guard let dir = directory else { return }
        // Reject oversized OSC 7 payloads before any URL parsing or filesystem work.
        // A crafted multi-megabyte payload would cause unbounded heap allocation
        // inside URL(string:) and potentially expensive subsequent fs calls.
        // 4096 bytes is generous for any real working directory path.
        guard dir.utf8.count <= 4096 else {
            securityLog.warning("OSC 7 cwd payload exceeds 4096 bytes (\(dir.utf8.count, privacy: .public)); ignoring")
            return
        }
        // SwiftTerm passes a file:// URL; extract the plain POSIX path.
        let path = URL(string: dir)?.path ?? dir
        // Validate before storing. An adversarial PTY could emit crafted OSC 7 payloads
        // to redirect resolveOpenableURL() (used for relative OSC 8 targets) to any
        // existing path on disk — e.g. pointing it at /tmp/payload then sending an
        // OSC 8 link of "file.txt" would open /tmp/payload/file.txt.
        guard !path.isEmpty, !path.contains("\0") else { return }
        // Restrict to home subtree so a crafted OSC 7 cannot give currentCwd full
        // filesystem reach and redirect subsequent OSC 8 link opens outside ~/…
        // Resolve symlinks in both paths before comparing so a symlink inside home
        // that points outside (possible on case-insensitive APFS) cannot bypass
        // the containment check via hasPrefix on the un-resolved strings.
        let resolvedPath = URL(fileURLWithPath: path).resolvingSymlinksInPath().path
        let home = URL(fileURLWithPath: FileManager.default.homeDirectoryForCurrentUser.path)
            .resolvingSymlinksInPath().path
        guard resolvedPath == home || resolvedPath.hasPrefix(home + "/") else { return }
        var isDir: ObjCBool = false
        guard FileManager.default.fileExists(atPath: resolvedPath, isDirectory: &isDir),
              isDir.boolValue else { return }
        Task { @MainActor [weak self] in
            self?.currentCwd = resolvedPath
        }
    }

    nonisolated func processTerminated(source: TerminalView, exitCode: Int32?) {
        Task { @MainActor [weak self] in
            self?.onClose?()
        }
    }
}


